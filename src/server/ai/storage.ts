import "server-only";
import { createHmac, timingSafeEqual } from "node:crypto";
import { mkdir, readFile, writeFile, unlink } from "node:fs/promises";
import path from "node:path";
import {
  S3Client,
  PutObjectCommand,
  GetObjectCommand,
  DeleteObjectCommand,
  DeleteObjectsCommand,
} from "@aws-sdk/client-s3";
import { getSignedUrl } from "@aws-sdk/s3-request-presigner";
import { z } from "zod";
import { getServerEnv } from "../env";
import { ApiError } from "../api-error";

import { MAX_DOCUMENT_FILE_BYTES } from "@/features/ai-generate/lib/document-limits";
export const MAX_UPLOAD_BYTES = MAX_DOCUMENT_FILE_BYTES;
const root = path.join(process.cwd(), ".data", "uploads");
function localPath(key: string) {
  // Storage identifiers are generated by the server; never accept arbitrary paths.
  if (!/^uploads\/[0-9a-f-]{36}$/.test(key)) throw new ApiError(400, "VALIDATION_ERROR");
  z.uuid().parse(key.slice(8));
  return path.join(root, key.slice(8));
}
let s3Instance: S3Client | undefined;
function client() {
  const env = getServerEnv();
  if (!env.S3_ENDPOINT) {
    if (env.NODE_ENV === "production" && env.DEPLOYMENT_ENV !== "local")
      throw new ApiError(503, "STORAGE_UNAVAILABLE");
    return null;
  }
  return (s3Instance ??= new S3Client({
    endpoint: env.S3_ENDPOINT,
    region: env.S3_REGION,
    credentials: { accessKeyId: env.S3_ACCESS_KEY_ID!, secretAccessKey: env.S3_SECRET_ACCESS_KEY! },
    forcePathStyle: true,
    // SDK defaults bake a CRC32 of the *empty* body into presigned PUT URLs, so S3-compatible
    // stores (Supabase, R2) reject the browser's real upload. Only checksum when an API demands it.
    requestChecksumCalculation: "WHEN_REQUIRED",
    responseChecksumValidation: "WHEN_REQUIRED",
  }));
}
function signature(id: string, size: number, mime: string, expires: number) {
  return createHmac("sha256", getServerEnv().BETTER_AUTH_SECRET!)
    .update(`${id}\n${size}\n${mime}\n${expires}`)
    .digest("hex");
}
export async function presignUpload(id: string, key: string, size: number, mime: string) {
  const s3 = client();
  if (s3)
    return getSignedUrl(
      s3,
      new PutObjectCommand({
        Bucket: getServerEnv().S3_BUCKET,
        Key: key,
        ContentType: mime,
        ContentLength: size,
      }),
      { expiresIn: 300 },
    );
  const expires = Math.floor(Date.now() / 1000) + 300;
  return `/api/v1/ai/uploads/${id}/file?${new URLSearchParams({ expires: String(expires), signature: signature(id, size, mime, expires) })}`;
}
export function verifyUploadSignature(
  id: string,
  size: number,
  mime: string,
  query: URLSearchParams,
) {
  const expires = Number(query.get("expires"));
  const received = query.get("signature") ?? "";
  if (
    !Number.isSafeInteger(expires) ||
    expires < Date.now() / 1000 ||
    expires > Date.now() / 1000 + 301 ||
    !/^[a-f0-9]{64}$/.test(received)
  )
    throw new ApiError(403, "FORBIDDEN");
  if (
    !timingSafeEqual(
      Buffer.from(received, "hex"),
      Buffer.from(signature(id, size, mime, expires), "hex"),
    )
  )
    throw new ApiError(403, "FORBIDDEN");
}
export async function putLocalFile(key: string, bytes: Buffer) {
  if (client()) throw new ApiError(404, "NOT_FOUND");
  await mkdir(root, { recursive: true, mode: 0o700 });
  await writeFile(localPath(key), bytes, { mode: 0o600, flag: "wx" }).catch(() => {
    throw new ApiError(409, "CONFLICT");
  });
}
export async function getUpload(
  key: string,
  expectedSize: number,
  signal?: AbortSignal,
): Promise<Buffer> {
  const s3 = client();
  if (!s3) {
    const bytes = await readFile(localPath(key)).catch(() => {
      throw new ApiError(400, "UPLOAD_MISSING");
    });
    if (bytes.length !== expectedSize || bytes.length > MAX_UPLOAD_BYTES)
      throw new ApiError(400, "INVALID_FILE");
    return bytes;
  }
  const object = await s3.send(
    new GetObjectCommand({ Bucket: getServerEnv().S3_BUCKET, Key: key }),
    { abortSignal: signal },
  );
  if (object.ContentLength !== expectedSize || expectedSize > MAX_UPLOAD_BYTES || !object.Body)
    throw new ApiError(400, "INVALID_FILE");
  const bytes = Buffer.from(await object.Body.transformToByteArray());
  if (bytes.length !== expectedSize) throw new ApiError(400, "INVALID_FILE");
  return bytes;
}
export async function deleteUpload(key: string) {
  const s3 = client();
  if (s3) await s3.send(new DeleteObjectCommand({ Bucket: getServerEnv().S3_BUCKET, Key: key }));
  else
    await unlink(localPath(key)).catch((error) => {
      if (error.code !== "ENOENT") throw error;
    });
}
/** S3 DeleteObjects accepts at most this many keys per request. */
export const DELETE_BATCH_SIZE = 1000;
async function deleteObjectBatch(s3: S3Client, keys: string[]) {
  const result = await s3.send(
    new DeleteObjectsCommand({
      Bucket: getServerEnv().S3_BUCKET,
      Delete: { Objects: keys.map((Key) => ({ Key })), Quiet: true },
    }),
  );
  const failed = new Set((result.Errors ?? []).map((error) => error.Key));
  return keys.filter((key) => !failed.has(key));
}
/**
 * Deletes stored objects in batches and returns the keys that are gone, so callers only drop
 * the database rows whose object really left storage (a missing object counts as gone).
 */
export async function deleteStoredObjects(keys: readonly string[]): Promise<string[]> {
  const s3 = client();
  if (!s3) {
    const results = await Promise.allSettled(keys.map((key) => deleteUpload(key)));
    return keys.filter((_, index) => results[index].status === "fulfilled");
  }
  const batches = Array.from({ length: Math.ceil(keys.length / DELETE_BATCH_SIZE) }, (_, index) =>
    keys.slice(index * DELETE_BATCH_SIZE, (index + 1) * DELETE_BATCH_SIZE),
  );
  const deleted: string[][] = [];
  for (const batch of batches) deleted.push(await deleteObjectBatch(s3, batch));
  return deleted.flat();
}
export async function readBinary(request: Request, size: number) {
  if (size > MAX_UPLOAD_BYTES) throw new ApiError(413, "INVALID_FILE");
  const reader = request.body?.getReader();
  if (!reader) throw new ApiError(400, "INVALID_FILE");
  const parts: Uint8Array[] = [];
  let count = 0;
  try {
    while (true) {
      const { done, value } = await reader.read();
      if (done) break;
      count += value.length;
      if (count > size) {
        await reader.cancel();
        throw new ApiError(413, "INVALID_FILE");
      }
      parts.push(value);
    }
    if (count !== size) throw new ApiError(400, "INVALID_FILE");
    return Buffer.concat(parts);
  } finally {
    reader.releaseLock();
  }
}

/** Private permanent card assets use the same S3 adapter, outside upload expiry records. */
export async function putStoredFile(
  key: string,
  bytes: Buffer,
  mime: string,
  signal?: AbortSignal,
) {
  const s3 = client();
  if (s3)
    await s3.send(
      new PutObjectCommand({
        Bucket: getServerEnv().S3_BUCKET,
        Key: key,
        Body: bytes,
        ContentType: mime,
      }),
      { abortSignal: signal },
    );
  else await putLocalFile(key, bytes);
}
